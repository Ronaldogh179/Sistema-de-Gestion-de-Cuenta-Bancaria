import { Router } from 'express';
import * as controller from '../controllers/cuentaController.js';
const router = Router();
router.get('/cuentas', controller.listar);
router.post('/cuenta/deposito', controller.deposito);
router.post('/cuenta/retiro', controller.retiro);
router.post('/cuenta/transferencia', controller.transferencia);
router.get('/cuenta/:id/historial', controller.historial);
router.get('/cuenta/:id', controller.detalle);
export default router;
